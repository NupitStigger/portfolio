// Список текстовых узлов, которые можно перевести
const nodes = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const n = walker.currentNode;
  const m = n.nodeValue.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (T[m[2]]) nodes.push({ n, ru: m[2], a: m[1], b: m[3] });
}
const h1 = document.querySelector('h1');
const nameInput = form.querySelector('input[type=text]');
const up = document.getElementById('up');

function setLang(l) {
  const i = l === 'kk' ? 0 : 1;
  nodes.forEach(o => { o.n.nodeValue = o.a + (l === 'ru' ? o.ru : T[o.ru][i]) + o.b; });
  h1.innerHTML = M.h1[l];
  document.title = M.title[l];
  nameInput.placeholder = M.ph[l];
  up.setAttribute('aria-label', M.up[l]);
  document.documentElement.lang = l;
  document.querySelectorAll('.lang button').forEach(b => b.classList.toggle('on', b.dataset.l === l));
  try { localStorage.setItem('lang', l); } catch (e) {}
}
document.querySelectorAll('.lang button').forEach(b => b.addEventListener('click', () => setLang(b.dataset.l)));
let saved = 'ru';
try { saved = localStorage.getItem('lang') || 'ru'; } catch (e) {}
